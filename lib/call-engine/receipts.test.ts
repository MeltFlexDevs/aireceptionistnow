import test from "node:test";
import assert from "node:assert/strict";

import {
  appendReceiptLink,
  deservesReceipt,
  DEMO_RECEIPT_TTL_DAYS,
  isReceiptToken,
  mintReceiptToken,
  receiptExpiry,
  receiptSmsBody,
  receiptUrl,
  RECEIPT_TTL_DAYS,
} from "./receipts";

test("minted tokens are unguessable and round-trip the validator", () => {
  const seen = new Set<string>();
  for (let i = 0; i < 500; i++) {
    const token = mintReceiptToken();
    assert.ok(isReceiptToken(token), `${token} should be accepted`);
    assert.ok(!seen.has(token), "tokens must not repeat");
    seen.add(token);
  }
});

test("the token validator rejects anything that is not one of ours", () => {
  // This runs before the database lookup, so it is what stops /r/<garbage> from
  // becoming a free text-search oracle.
  for (const bad of ["", "short", "has spaces", "has/slash", "a".repeat(65), "tok+en", "../etc"]) {
    assert.equal(isReceiptToken(bad), false, `${JSON.stringify(bad)} must be rejected`);
  }
  for (const bad of [null, undefined, 42, {}, []]) {
    assert.equal(isReceiptToken(bad), false);
  }
});

test("a demo receipt expires far sooner than a customer's", () => {
  // The demo number is printed on a marketing page, so its receipts are
  // generated by strangers and must not accumulate as pages we host forever.
  const now = new Date("2026-08-11T09:00:00Z");
  const live = receiptExpiry("live", now).getTime() - now.getTime();
  const demo = receiptExpiry("demo", now).getTime() - now.getTime();
  assert.equal(live, RECEIPT_TTL_DAYS * 86_400_000);
  assert.equal(demo, DEMO_RECEIPT_TTL_DAYS * 86_400_000);
  assert.ok(demo < live);
});

test("the receipt URL is absolute when a base is configured and never doubles a slash", () => {
  assert.equal(receiptUrl("abc", "https://example.com"), "https://example.com/r/abc");
  assert.equal(receiptUrl("abc", "https://example.com/"), "https://example.com/r/abc");
  // No base configured: still a usable path rather than a URL starting "/r"
  // glued onto nothing.
  assert.equal(receiptUrl("abc", ""), "/r/abc");
});

test("the SMS leads with the business name, not ours", () => {
  const body = receiptSmsBody("Bright Dental", "https://example.com/r/abc");
  assert.ok(body.startsWith("Bright Dental"), "a text from an unknown brand reads as spam");
  assert.ok(body.includes("https://example.com/r/abc"));
});

test("a booking confirmation with no receipt link is left exactly as it was", () => {
  const confirmation = "Hi Ana, you're booked for Thursday at 9am. See you then!";
  assert.equal(appendReceiptLink(confirmation, ""), confirmation);
  assert.equal(
    appendReceiptLink(confirmation, "https://example.com/r/abc"),
    `${confirmation} Details: https://example.com/r/abc`,
  );
});

test("only calls that produced something get a receipt", () => {
  assert.equal(deservesReceipt("booked", false), true);
  assert.equal(deservesReceipt("message", false), true);
  assert.equal(deservesReceipt("transferred", false), true);
  // Answering a question is not on its own worth a text message.
  assert.equal(deservesReceipt("resolved", false), false);
  // ...unless the audit thinks a human should read the call, which is exactly
  // the case where the caller may have been told something wrong.
  assert.equal(deservesReceipt("resolved", true), true);
});

test("a caller who hung up is never texted, however the call was flagged", () => {
  // The one hard rule: someone who chose to leave must not get a link about it.
  assert.equal(deservesReceipt("abandoned", false), false);
  assert.equal(deservesReceipt("abandoned", true), false);
});
