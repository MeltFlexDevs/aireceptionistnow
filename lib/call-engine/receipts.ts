/**
 * Call receipts — the caller's copy of what just happened.
 *
 * Every other output of a call points at the business. The receipt points at the
 * person who rang, and it exists for one reason: they are the only party who
 * knows whether the assistant actually got it right. The post-call accuracy
 * audit compares what the assistant said against the knowledge base, which
 * catches an invented price but never catches a misheard house number — nothing
 * in the knowledge base contradicts it, because the caller supplied it.
 *
 * So the receipt asks them. It renders the recap in the caller's own language,
 * lists what was committed to, and offers one button that says it is wrong.
 *
 * Kept free of I/O so the token rules can be tested directly — see
 * receipts.test.ts.
 */

import crypto from "node:crypto";

/**
 * How long a receipt link stays live.
 *
 * Long enough to survive a caller who reads their texts that evening or over a
 * weekend, short enough that a link forwarded into a group chat or pasted into a
 * support ticket stops working well before anyone thinks to try it. The page is
 * unauthenticated — expiry is the only revocation it has.
 */
export const RECEIPT_TTL_DAYS = 30;

/**
 * The public demo number's receipts. Days, not weeks: these are generated by
 * anyone who dials a number printed on a marketing page, so the corpus grows
 * without bound and every row is a page we host on a stranger's behalf.
 */
export const DEMO_RECEIPT_TTL_DAYS = 7;

export type ReceiptKind = "live" | "demo";

/**
 * 160 bits, base64url. Minted rather than derived from the call id: a token that
 * is a function of a guessable input is a guessable token, and this one is the
 * page's entire access control.
 *
 * Not an HMAC of the call id for the same reason — an attacker who learns the
 * scheme and one (id, token) pair learns nothing here, because there is no
 * scheme to learn. The token is random and the database is the authority.
 */
export function mintReceiptToken(): string {
  return crypto.randomBytes(20).toString("base64url");
}

/**
 * Reject anything that is not shaped like one of our tokens before it reaches
 * the database. Cheap, and it keeps the lookup from being a free text-search
 * oracle for anyone hammering /r/<garbage>.
 */
export function isReceiptToken(value: unknown): value is string {
  return typeof value === "string" && /^[A-Za-z0-9_-]{20,64}$/.test(value);
}

export function receiptExpiry(kind: ReceiptKind, now = new Date()): Date {
  const days = kind === "demo" ? DEMO_RECEIPT_TTL_DAYS : RECEIPT_TTL_DAYS;
  return new Date(now.getTime() + days * 86_400_000);
}

/**
 * The link that goes in the SMS.
 *
 * Deliberately short and path-shaped (`/r/<token>`): the receipt travels inside a
 * text message alongside a booking confirmation, where every character is either
 * a segment boundary or a reason the carrier's filter looks harder.
 */
export function receiptUrl(token: string, baseUrl = process.env.APP_BASE_URL ?? ""): string {
  const base = baseUrl.replace(/\/$/, "");
  return base ? `${base}/r/${token}` : `/r/${token}`;
}

/**
 * What the caller is told when the receipt is the only message they get.
 *
 * One sentence, the business's name first so it does not read as spam, and the
 * bare link. No marketing, no sender branding beyond the name they just called:
 * a promotional-looking SMS to someone who rang a plumber is how a number gets
 * reported, and a reported number stops delivering for every other tenant.
 */
export function receiptSmsBody(businessName: string, url: string): string {
  return `${businessName}: here's a summary of your call, and a way to tell us if we got anything wrong - ${url}`;
}

/**
 * The same link appended to a booking confirmation the caller is already
 * getting. Merged rather than sent separately: two texts about one phone call is
 * the point at which a helpful artifact becomes a nuisance.
 */
export function appendReceiptLink(body: string, url: string): string {
  return url ? `${body} Details: ${url}` : body;
}

/**
 * Is this call worth a receipt at all?
 *
 * A receipt for "sorry, we're closed" is a text message nobody asked for. The
 * bar is that the assistant did something with consequences the caller would
 * want in writing — booked, took a message, or promised a follow-up — or that
 * the audit already thinks a human should look at the call.
 *
 * `abandoned` is excluded even when flagged: the caller hung up, and texting a
 * link to someone who chose to leave is the worst version of this feature.
 */
export function deservesReceipt(outcome: string, needsReview: boolean): boolean {
  if (outcome === "abandoned") return false;
  return outcome === "booked" || outcome === "message" || outcome === "transferred" || needsReview;
}
